CREATE TABLE budgets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL,
                         category_id BIGINT,
                         amount NUMERIC(19,2) NOT NULL,
                         month SMALLINT NOT NULL,
                         year SMALLINT NOT NULL,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT fk_budgets_user
                             FOREIGN KEY (user_id)
                                 REFERENCES users(id)
                                 ON DELETE CASCADE,

                         CONSTRAINT fk_budgets_category
                             FOREIGN KEY (category_id)
                                 REFERENCES categories(id)
                                 ON DELETE RESTRICT,

                         CONSTRAINT chk_budgets_amount
                             CHECK (amount > 0),

                         CONSTRAINT chk_budgets_month
                             CHECK (month BETWEEN 1 AND 12),

    CONSTRAINT chk_budgets_year
        CHECK (year >= 2000)
);

CREATE UNIQUE INDEX uq_budgets_category_period
    ON budgets (user_id, category_id, month, year)
    WHERE category_id IS NOT NULL;

CREATE UNIQUE INDEX uq_budgets_general_period
    ON budgets (user_id, month, year)
    WHERE category_id IS NULL;

CREATE INDEX idx_budgets_user_period
    ON budgets (user_id, year, month);

CREATE INDEX idx_budgets_category
    ON budgets (category_id);
